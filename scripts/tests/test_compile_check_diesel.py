"""Tests for scripts/compile_check_diesel.py. cargo and node are never run: `which` and `run` are faked."""

from __future__ import annotations

import io
import subprocess
import sys
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import compile_check_diesel as ccd  # noqa: E402

PG = 'datasource db {\n  provider = "postgresql"\n}\n\nmodel A {\n  id Int @id\n}\n'


class FakeRun:
    """Records commands; the prismax CLI writes empty files, cargo exits with `cargo_code`."""

    def __init__(self, cargo_code: int = 0, cli_code: int = 0) -> None:
        self.cargo_code = cargo_code
        self.cli_code = cli_code
        self.calls: list[tuple[list[str], dict]] = []

    def __call__(self, command, **kwargs) -> subprocess.CompletedProcess:
        self.calls.append((list(command), kwargs))
        if command[1].endswith("cli.js"):
            out = Path(command[command.index("--out") + 1])
            (out / "schema.rs").write_text("")
            (out / "models.rs").write_text("")
            return subprocess.CompletedProcess(command, self.cli_code, "", "boom" if self.cli_code else "")
        return subprocess.CompletedProcess(command, self.cargo_code, "", "")


def which_all(name: str) -> str:
    return f"/usr/bin/{name}"


class HelpersTest(unittest.TestCase):
    def test_detect_provider(self) -> None:
        self.assertEqual(ccd.detect_provider(PG), "postgresql")
        self.assertEqual(ccd.detect_provider('datasource db {\n  url = "x"\n  provider = "sqlite"\n}'), "sqlite")
        self.assertIsNone(ccd.detect_provider("model A {\n  id Int @id\n}"))
        self.assertIsNone(ccd.detect_provider('generator client {\n  provider = "prisma-client-js"\n}'))

    def test_module_name(self) -> None:
        self.assertEqual(ccd.module_name(Path("test/fixtures/Many-To-Many.prisma")), "fixture_many_to_many")

    def test_group_fixtures(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            files = {
                "b.prisma": PG,
                "a.prisma": PG,
                "c.prisma": PG.replace("postgresql", "sqlite"),
                "mongo.prisma": PG.replace("postgresql", "mongodb"),
                "none.prisma": "model A {\n  id Int @id\n}\n",
            }
            for name, text in files.items():
                (root / name).write_text(text)
            groups, skipped = ccd.group_fixtures([root / name for name in files])
            self.assertEqual({k: [p.name for p in v] for k, v in groups.items()}, {
                "postgresql": ["a.prisma", "b.prisma"],
                "sqlite": ["c.prisma"],
            })
            self.assertEqual(skipped, [
                "skip mongo.prisma: provider 'mongodb' has no Diesel backend",
                "skip none.prisma: provider None has no Diesel backend",
            ])

    def test_cargo_toml(self) -> None:
        toml = ccd.cargo_toml("mysql")
        self.assertIn('diesel = { version = "2.2", features = ["mysql", "chrono", "serde_json", "uuid", "numeric"] }', toml)
        self.assertIn('bigdecimal = "0.4"', toml)
        self.assertIn('name = "prismax-compile-check-mysql"', toml)

    def test_lib_rs(self) -> None:
        self.assertEqual(
            ccd.lib_rs(["fixture_a", "fixture_b"]),
            "// Generated by scripts/compile_check_diesel.py.\n#![allow(dead_code)]\n\npub mod fixture_a;\npub mod fixture_b;\n",
        )


class CheckEnvTest(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.workdir = Path(self._tmp.name)

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def test_defaults_the_target_dir_to_the_workdir(self) -> None:
        env = ccd.check_env("postgresql", {"PATH": "/bin"}, self.workdir)
        self.assertEqual(env, {"PATH": "/bin", "CARGO_TARGET_DIR": str(self.workdir / "target")})

    def test_respects_cargo_target_dir(self) -> None:
        env = ccd.check_env("sqlite", {"CARGO_TARGET_DIR": "/cache/target"}, self.workdir)
        self.assertEqual(env["CARGO_TARGET_DIR"], "/cache/target")

    def test_points_mysqlclient_at_a_placeholder(self) -> None:
        env = ccd.check_env("mysql", {}, self.workdir)
        self.assertTrue(Path(env["MYSQLCLIENT_LIB_DIR"]).is_dir())
        self.assertEqual(env["MYSQLCLIENT_VERSION"], "8.0.36")

    def test_keeps_a_configured_mysqlclient(self) -> None:
        env = ccd.check_env("mysql", {"MYSQLCLIENT_LIB_DIR": "/opt/mysql/lib"}, self.workdir)
        self.assertEqual(env["MYSQLCLIENT_LIB_DIR"], "/opt/mysql/lib")
        self.assertNotIn("MYSQLCLIENT_VERSION", env)

    def test_does_not_modify_the_base_environment(self) -> None:
        base = {"PATH": "/bin"}
        ccd.check_env("mysql", base, self.workdir)
        self.assertEqual(base, {"PATH": "/bin"})


class CreateProjectTest(unittest.TestCase):
    def test_generates_one_module_per_fixture(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            fixture = root / "blog.prisma"
            fixture.write_text(PG)
            run = FakeRun()
            ccd.create_project(root / "pg", "postgresql", [fixture], run, "node")
            self.assertEqual(run.calls[0][0][2:], [
                "generate", "--adapter", "diesel", "--schema", str(fixture), "--out", str(root / "pg/src/fixture_blog"),
            ])
            self.assertEqual((root / "pg/src/fixture_blog/mod.rs").read_text(), ccd.MOD_RS)
            self.assertIn("pub mod fixture_blog;", (root / "pg/src/lib.rs").read_text())
            self.assertIn('features = ["postgres"', (root / "pg/Cargo.toml").read_text())

    def test_raises_when_the_cli_fails(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            fixture = Path(tmp) / "blog.prisma"
            fixture.write_text(PG)
            with self.assertRaisesRegex(RuntimeError, "prismax failed for blog.prisma \\(exit 1\\):\nboom"):
                ccd.create_project(Path(tmp) / "pg", "postgresql", [fixture], FakeRun(cli_code=1), "node")


class MainTest(unittest.TestCase):
    def main(self, argv, which=which_all, run=None) -> tuple[int, str, str]:
        stdout, stderr = io.StringIO(), io.StringIO()
        with redirect_stdout(stdout), redirect_stderr(stderr):
            code = ccd.main(argv, which=which, run=run or FakeRun())
        return code, stdout.getvalue(), stderr.getvalue()

    def test_skips_without_cargo(self) -> None:
        run = FakeRun()
        code, stdout, _ = self.main([], which=lambda name: None, run=run)
        self.assertEqual(code, 0)
        self.assertIn("cargo not found; skipping", stdout)
        self.assertEqual(run.calls, [])

    def test_fails_without_node(self) -> None:
        code, _, stderr = self.main([], which=lambda name: "/usr/bin/cargo" if name == "cargo" else None)
        self.assertEqual(code, 1)
        self.assertIn("node not found", stderr)

    def test_runs_cargo_check_per_provider(self) -> None:
        if not ccd.CLI.exists():
            self.skipTest("dist/cli.js is not built")
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "a.prisma").write_text(PG)
            (root / "b.prisma").write_text(PG.replace("postgresql", "sqlite"))
            run = FakeRun()
            code, stdout, _ = self.main([str(root / "a.prisma"), str(root / "b.prisma"), "--workdir", str(root / "work")], run=run)
            self.assertEqual(code, 0, stdout)
            cargo = [(call, kwargs) for call, kwargs in run.calls if call[0] == "/usr/bin/cargo"]
            self.assertEqual([kwargs["cwd"] for _, kwargs in cargo], [root / "work/postgresql", root / "work/sqlite"])
            self.assertEqual(cargo[0][0], ["/usr/bin/cargo", "check", "--quiet", "--message-format", "short"])
            self.assertIn("OK: generated Diesel code compiles", stdout)
            self.assertTrue((root / "work/postgresql/Cargo.toml").exists())

    def test_reports_cargo_failures(self) -> None:
        if not ccd.CLI.exists():
            self.skipTest("dist/cli.js is not built")
        with tempfile.TemporaryDirectory() as tmp:
            fixture = Path(tmp) / "a.prisma"
            fixture.write_text(PG)
            code, _, stderr = self.main([str(fixture)], run=FakeRun(cargo_code=101))
            self.assertEqual(code, 1)
            self.assertIn("FAILED: postgresql", stderr)


if __name__ == "__main__":
    unittest.main()
