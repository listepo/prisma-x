/** Small helpers shared by adapters. Not part of the core. */
import type { IrColumnField, IrModel } from '../core/ir.js';

/** Returns `base`, or `base` with `_` appended until it is not in `taken`; records the result. */
export function claim(base: string, taken: Set<string>): string {
  let name = base;
  while (taken.has(name)) name += '_';
  taken.add(name);
  return name;
}

/** Replaces characters that cannot appear in an identifier and avoids a leading digit. */
export function identifier(name: string, fallback: string): string {
  const cleaned = name.replace(/[^\p{L}\p{N}_]/gu, '_');
  if (cleaned === '' || /^_*$/u.test(cleaned)) return fallback;
  return /^\p{N}/u.test(cleaned) ? `_${cleaned}` : cleaned;
}

export function columnFields(model: IrModel): IrColumnField[] {
  return model.fields.filter((f): f is IrColumnField => f.kind === 'scalar' || f.kind === 'enum');
}

export function docLines(documentation: string | null): string[] {
  return documentation === null ? [] : documentation.split('\n');
}

/** Header line for generated files. */
export function generatedBy(adapter: string): string {
  return `@generated by prisma-x (${adapter} adapter). Do not edit by hand.`;
}
